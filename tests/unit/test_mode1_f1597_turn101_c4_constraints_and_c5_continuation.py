import json
import unittest
from pathlib import Path

REPO_ROOT = Path("D:/Master thesis/Adaptive remeshing")
AUDIT_JSON_PATH = REPO_ROOT / "results/validation/mode1_f1597/turn101_c4_constraint_and_c5_continuation_audit.json"

class TestTurn101C4ConstraintsAndC5Continuation(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not AUDIT_JSON_PATH.exists():
            raise FileNotFoundError(f"Missing {AUDIT_JSON_PATH}")
        with open(AUDIT_JSON_PATH, "r", encoding="utf-8") as f:
            cls.data = json.load(f)

    def test_schema_and_metadata(self):
        self.assertEqual(self.data.get("schema"), 1)
        self.assertEqual(self.data.get("task_id"), "F1597-CORRECT-PACKAGE72-STATE-TRANSFER")
        self.assertEqual(self.data.get("turn"), 101)

    def test_section_2_c4_donor_audit(self):
        sec2 = self.data["section_2_c4_donor_audit"]
        self.assertEqual(sec2["closure_classification"], "FAIL")
        self.assertAlmostEqual(sec2["res_inf_free_set"], 1.521347e-05, delta=1.0e-7)
        self.assertAlmostEqual(sec2["binding_criterion_kNmm"], 1.0e-06, delta=1.0e-8)
        self.assertAlmostEqual(sec2["ratio_vs_criterion"], 15.2135, delta=0.01)
        self.assertEqual(sec2["num_prescribed_nodes"], 3845)
        self.assertEqual(sec2["num_free_nodes"], 743)

        n2277 = sec2["node_2277_detail"]
        self.assertEqual(n2277["node_id"], 2277)
        self.assertAlmostEqual(n2277["x_mm"], 0.0406, delta=0.001)
        self.assertAlmostEqual(n2277["y_mm"], 0.0500, delta=0.001)
        self.assertAlmostEqual(n2277["residual_R_kNmm"], 1.521347e-05, delta=1.0e-7)
        self.assertAlmostEqual(n2277["relative_residual_pct"], 4.2236, delta=0.01)

    def test_section_3_constraint_separation(self):
        sec3 = self.data["section_3_constraint_separation"]
        self.assertEqual(sec3["total_artificial_corridor_nodes"], 3845)
        self.assertEqual(sec3["far_field_wake_clamped_nodes"], 3845)

    def test_section_4_controlled_continuation_comparison(self):
        sec4 = self.data["section_4_controlled_continuation"]
        case_a = sec4["case_A_physical_only"]
        case_b = sec4["case_B_diagnostic_corridor"]

        # Case A: Severe over-softening tearing cascade
        self.assertFalse(case_a["converged"])
        self.assertAlmostEqual(case_a["rf2_final_N"], 73.2726, delta=0.1)
        self.assertAlmostEqual(case_a["delta_rf2_N"], -39.7260, delta=0.1)
        self.assertAlmostEqual(case_a["delta_rf2_pct"], -35.1562, delta=0.1)
        self.assertGreater(case_a["delta_e_frac_pct"], 28.0)
        self.assertAlmostEqual(case_a["max_advance_delta_d"], 0.495181, delta=0.01)

        # Case B: Stabilized physical softening
        self.assertFalse(case_b["converged"])
        self.assertAlmostEqual(case_b["rf2_final_N"], 108.2563, delta=0.1)
        self.assertAlmostEqual(case_b["delta_rf2_N"], -4.7423, delta=0.1)
        self.assertAlmostEqual(case_b["delta_rf2_pct"], -4.1968, delta=0.1)
        self.assertLess(case_b["delta_e_frac_pct"], 5.0)
        self.assertAlmostEqual(case_b["max_advance_delta_d"], 0.113268, delta=0.01)

        # Force stabilization proof: Case B retains 34.98 N more load capacity than Case A
        self.assertGreater(case_b["rf2_final_N"] - case_a["rf2_final_N"], 34.0)

if __name__ == "__main__":
    unittest.main()
