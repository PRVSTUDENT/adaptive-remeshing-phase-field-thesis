def test_04_package_61_manifest_and_frozen_subroutine():
    """Verify Package 61 model deck, manifest, and frozen UEL integrity."""
    pkg61_dir = REPO_ROOT / "models" / "pandey_kumar_mode1" / "61_method_c_stage_c1_2_cycle3_continuation"
    assert pkg61_dir.exists(), f"Missing Package 61 dir: {pkg61_dir}"

    uel_path = pkg61_dir / "f42_mixed_uel.for"
    assert uel_path.exists()
    uel_sha = hashlib.sha256(uel_path.read_bytes()).hexdigest().upper()
    assert uel_sha == "CE8D5EDCD2911DCB018BB15275271F874E7EA62B8FB48CF4A8297469A83ACDD6"

    deck_path = pkg61_dir / "M1_MC_STAGE_C1_2_CYCLE3_CONT.inp"
    assert deck_path.exists()
    deck_sha = hashlib.sha256(deck_path.read_bytes()).hexdigest().lower()

    manifest_path = pkg61_dir / "METHOD_C_STAGE_C1_2_CYCLE3_AUTHORIZATION.json"
    assert manifest_path.exists()
    with open(manifest_path, "r", encoding="utf-8") as fp:
        manifest = json.load(fp)

    jobs = manifest["jobs"]
    job = jobs[0]
    assert job["id"] == "M1_MC_STAGE_C1_2_CYCLE3_CONT"
    assert job["input"] == "M1_MC_STAGE_C1_2_CYCLE3_CONT.inp"
    assert manifest["files"]["M1_MC_STAGE_C1_2_CYCLE3_CONT.inp"] == deck_sha
    assert manifest["files"]["f42_mixed_uel.for"] == uel_sha.lower()

def test_05_checkpoint_energy_conservation_case_b_vs_c():
    """Verify machine-level energy continuity between Case B (control) and Case C (continuation) at u = 0.0012 mm."""
    # Case B Step 2 inc 200 measured values
    e_elas_B = 0.0990958  # mJ
    e_tot_B  = 0.0992109  # mJ

    # Case C Step 1 measured values
    e_elas_C = 0.0990944  # mJ
    e_tot_C  = 0.0992115  # mJ

    pct_diff_elas = abs(e_elas_C - e_elas_B) / e_elas_B * 100.0
    pct_diff_tot  = abs(e_tot_C - e_tot_B) / e_tot_B * 100.0

    assert pct_diff_elas < 0.010, f"Elastic energy diff {pct_diff_elas:.4f}% exceeds 0.010%"
    assert pct_diff_tot < 0.010, f"Total energy diff {pct_diff_tot:.4f}% exceeds 0.010%"
