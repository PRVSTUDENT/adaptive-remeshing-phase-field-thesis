#!/usr/bin/env python3
import os
import hashlib
import csv
from datetime import datetime

def sha256_file(filepath):
    h = hashlib.sha256()
    with open(filepath, 'rb') as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest().upper()

