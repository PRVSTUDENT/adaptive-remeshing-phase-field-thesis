import math
import argparse
from pathlib import Path

# Canonical donor state values at u = 0.0050 mm (Job 1411891 / M1_PRE_1S, 2,906 elements)
CANONICAL_DONOR_BENCHMARK = {
    "job_name": "M1_PRE_1S",
    "u_rp_mm": 0.005000,
    "rf_rp_N": 653.0886,
    "total_e_elas_mJ": 1.6327,
    "total_e_frac_mJ": 0.0307,
    "total_e_tot_mJ": 1.6634,
    "max_d_elem": 0.094910,
    "max_d_nodal": 0.094910,
    "min_H": 0.0,
    "num_elements": 2906,
    "num_nodes": 2988
}

ACCEPTANCE_THRESHOLDS = {
    "max_delta_rf_n": 0.50,              # Strict force continuity threshold (N)
    "target_delta_rf_n": 0.10,           # Target force continuity threshold (N)
    "max_rel_e_elas_pct": 0.50,          # Elastic energy disparity (%)
    "max_rel_e_frac_pct": 0.50,          # Fracture energy disparity (%)
    "max_rel_e_tot_pct": 0.50,           # Total energy disparity (%)
    "max_delta_d_peak": 1.0e-4,          # Peak damage difference
    "max_rel_integral_d_pct": 0.05,      # Relative damage integral error (%)
    "min_h_allowed": 0.0,                # History field non-negativity
    "max_irreversibility_violation": 1.0e-6 # Allowed numerical precision slack
}


def load_donor_state(donor_json_path):
    """Loads authentic donor state from JSON artifact."""
    if not os.path.exists(donor_json_path):
        raise FileNotFoundError(f"Donor JSON not found: {donor_json_path}")
    with open(donor_json_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data


def parse_sta_file(sta_path):
    """Parses Abaqus .sta file to extract step, increment, time, and cutback telemetry."""
    if not os.path.exists(sta_path):
        return None
    records = []
    with open(sta_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) >= 6 and parts[0].isdigit() and parts[1].isdigit():
                try:
                    step = int(parts[0])
                    inc = int(parts[1])
                    att = int(parts[2])
                    severe_discon = int(parts[3])
                    equil_iters = int(parts[4])
                    total_iters = int(parts[5])
                    step_time = float(parts[6]) if len(parts) > 6 else 0.0
                    inc_size = float(parts[7]) if len(parts) > 7 else 0.0
                    records.append({
                        "step": step,
                        "increment": inc,
                        "attempts": att,
                        "severe_discon": severe_discon,
                        "equil_iters": equil_iters,
                        "total_iters": total_iters,
                        "step_time": step_time,
                        "inc_size": inc_size
                    })
                except (ValueError, IndexError):
                    continue
    return records


def parse_energy_csv(csv_path):
    """Parses uel_energy_balance.csv generated by UEXTERNALDB."""
    if not os.path.exists(csv_path):
        return None
    records = []
    with open(csv_path, "r", encoding="utf-8") as f:
        header = f.readline().strip().split(",")
        for line in f:
            parts = line.strip().split(",")
            if len(parts) >= 7:
                try:
                    records.append({
                        "step": int(parts[0]),
                        "increment": int(parts[1]),
                        "total_time": float(parts[2]),
                        "step_time": float(parts[3]),
                        "e_elastic_mJ": float(parts[4]) * 1000.0,
                        "e_fracture_mJ": float(parts[5]) * 1000.0,
                        "e_total_mJ": float(parts[6]) * 1000.0
                    })
                except (ValueError, IndexError):
                    continue
    return records


def evaluate_stage_c1_0(donor_data, recipient_handoff_data, recipient_continuation_data=None):
    """
    Evaluates Stage C1-0 against pre-declared acceptance criteria.
    """
    results = {
        "status": "PENDING",
        "criteria": {},
        "summary": {}
    }

    # 1. Reaction Force Continuity
    rf_donor = float(donor_data.get("rf_rp_N", CANONICAL_DONOR_BENCHMARK["rf_rp_N"]))
    rf_rec = float(recipient_handoff_data.get("rf_rp_N", 0.0))
    delta_rf = abs(rf_rec - rf_donor)
    crit1_pass = delta_rf <= ACCEPTANCE_THRESHOLDS["max_delta_rf_n"]
    results["criteria"]["criterion_1_force_continuity"] = {
        "description": "Step-boundary reaction force continuity at u = 0.0050 mm",
        "rf_donor_N": rf_donor,
        "rf_recipient_N": rf_rec,
        "delta_rf_N": delta_rf,
        "threshold_N": ACCEPTANCE_THRESHOLDS["max_delta_rf_n"],
        "target_threshold_N": ACCEPTANCE_THRESHOLDS["target_delta_rf_n"],
        "status": "PASS" if crit1_pass else "FAIL"
    }

    # 2. Damage Field Integrity
    d_max_donor = float(donor_data.get("max_d_nodal", CANONICAL_DONOR_BENCHMARK["max_d_nodal"]))
    d_max_rec = float(recipient_handoff_data.get("max_d_nodal", 0.0))
    delta_d_max = abs(d_max_rec - d_max_donor)
    crit2_pass = delta_d_max <= ACCEPTANCE_THRESHOLDS["max_delta_d_peak"]
    results["criteria"]["criterion_2_damage_field"] = {
        "description": "Peak nodal damage field match at u = 0.0050 mm",
        "d_max_donor": d_max_donor,
        "d_max_recipient": d_max_rec,
        "delta_d_max": delta_d_max,
        "threshold": ACCEPTANCE_THRESHOLDS["max_delta_d_peak"],
        "status": "PASS" if crit2_pass else "FAIL"
    }

    # 3. History Non-Negativity
    min_h_rec = float(recipient_handoff_data.get("min_H", 0.0))
    crit3_pass = min_h_rec >= ACCEPTANCE_THRESHOLDS["min_h_allowed"]
    results["criteria"]["criterion_3_history_nonnegativity"] = {
        "description": "Crack-driving history field H non-negativity (min(H) >= 0)",
        "min_H_recipient": min_h_rec,
        "threshold": ACCEPTANCE_THRESHOLDS["min_h_allowed"],
        "status": "PASS" if crit3_pass else "FAIL"
    }

    # 4. Energy Preservation
    e_elas_don = float(donor_data.get("total_e_elas_mJ", CANONICAL_DONOR_BENCHMARK["total_e_elas_mJ"]))
    e_elas_rec = float(recipient_handoff_data.get("total_e_elas_mJ", 0.0))
    rel_e_elas_pct = abs(e_elas_rec - e_elas_don) / e_elas_don * 100.0 if e_elas_don > 0 else 0.0

    e_frac_don = float(donor_data.get("total_e_frac_mJ", CANONICAL_DONOR_BENCHMARK["total_e_frac_mJ"]))
    e_frac_rec = float(recipient_handoff_data.get("total_e_frac_mJ", 0.0))
    rel_e_frac_pct = abs(e_frac_rec - e_frac_don) / e_frac_don * 100.0 if e_frac_don > 0 else 0.0

    e_tot_don = float(donor_data.get("total_e_tot_mJ", CANONICAL_DONOR_BENCHMARK["total_e_tot_mJ"]))
    e_tot_rec = float(recipient_handoff_data.get("total_e_tot_mJ", 0.0))
    rel_e_tot_pct = abs(e_tot_rec - e_tot_don) / e_tot_don * 100.0 if e_tot_don > 0 else 0.0

    crit4_pass = (rel_e_elas_pct <= ACCEPTANCE_THRESHOLDS["max_rel_e_elas_pct"] and
                  rel_e_frac_pct <= ACCEPTANCE_THRESHOLDS["max_rel_e_frac_pct"] and
                  rel_e_tot_pct <= ACCEPTANCE_THRESHOLDS["max_rel_e_tot_pct"])

    results["criteria"]["criterion_4_energy_preservation"] = {
        "description": "Global energy component preservation across handoff boundary",
        "e_elas_donor_mJ": e_elas_don,
        "e_elas_recipient_mJ": e_elas_rec,
        "rel_e_elas_pct": rel_e_elas_pct,
        "e_frac_donor_mJ": e_frac_don,
        "e_frac_recipient_mJ": e_frac_rec,
        "rel_e_frac_pct": rel_e_frac_pct,
        "e_tot_donor_mJ": e_tot_don,
        "e_tot_recipient_mJ": e_tot_rec,
        "rel_e_tot_pct": rel_e_tot_pct,
        "threshold_pct": ACCEPTANCE_THRESHOLDS["max_rel_e_tot_pct"],
        "status": "PASS" if crit4_pass else "FAIL"
    }

    # 5. Overall Handoff Status
    handoff_passed = crit1_pass and crit2_pass and crit3_pass and crit4_pass
    results["status"] = "STAGE_C1_0_HANDOFF_PASS" if handoff_passed else "STAGE_C1_0_HANDOFF_FAIL"

    return results


def main():
    parser = argparse.ArgumentParser(description="Evaluate Stage C1-0 continuation against acceptance criteria")
    parser.add_argument("--donor-json", default="models/pandey_kumar_mode1/41_method_c_genuine_continuation/evidence_forward_audit/coarse_donor_state_u0050.json",
                        help="Path to authentic donor state JSON")
    parser.add_argument("--recipient-json", default=None,
                        help="Path to recipient handoff evaluation JSON")
    parser.add_argument("--output-json", default="models/pandey_kumar_mode1/47_method_c_stage_c1_0_identical_mesh_continuation/stage_c1_0_evaluation.json",
                        help="Output evaluation JSON path")
    args = parser.parse_args()

    donor_data = load_donor_state(args.donor_json)
    print(f"[INFO] Loaded donor state from: {args.donor_json}")
    print(f"       RF: {donor_data.get('rf_rp_N')} N, E_tot: {donor_data.get('total_e_tot_mJ')} mJ, d_max: {donor_data.get('max_d_nodal')}")

    if args.recipient_json and os.path.exists(args.recipient_json):
        with open(args.recipient_json, "r", encoding="utf-8") as f:
            rec_data = json.load(f)
        eval_res = evaluate_stage_c1_0(donor_data, rec_data)
    else:
        print("[INFO] No recipient JSON provided. Staging benchmark evaluation specification.")
        eval_res = evaluate_stage_c1_0(donor_data, donor_data) # Self-consistency baseline
        eval_res["notes"] = "Baseline self-consistency check against canonical donor data."

    print(json.dumps(eval_res, indent=2))

    if args.output_json:
        os.makedirs(os.path.dirname(args.output_json), exist_ok=True)
        with open(args.output_json, "w", encoding="utf-8") as f:
            json.dump(eval_res, f, indent=2)
        print(f"[INFO] Saved evaluation to: {args.output_json}")


if __name__ == "__main__":
    main()
