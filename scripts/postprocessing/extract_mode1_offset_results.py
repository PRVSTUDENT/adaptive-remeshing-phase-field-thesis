#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Reusable post-processing extractor for Mode-I Kinematic-Offset UEL simulations.

Fixes the extraction-index bug where Step 2 endpoint reaction force was misassigned
to Step 1 reconstruction, and extracts comprehensive mechanical, damage, and energy
metrics across all solver steps and increments.
"""

import os
import re
import csv
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple


def parse_dat_rp_reactions(dat_path: str) -> List[Dict[str, Any]]:
    """
    Parse Abaqus .dat file for node 999999 (Reference Point) reaction force RF2 and U2.
    Accurately tracks step and increment transitions without assuming fixed table indices.
    """
    records = []
    current_step = None
    current_inc = None
    in_rp_table = False

    if not os.path.exists(dat_path):
        return records

    with open(dat_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            # Step and increment header detection
            m_step_inc = re.search(r"STEP\s+(\d+)\s+INCREMENT\s+(\d+)", line)
            if m_step_inc:
                current_step = int(m_step_inc.group(1))
                current_inc = int(m_step_inc.group(2))
            else:
                m_inc = re.search(r"INCREMENT\s+(\d+)\s+SUMMARY", line)
                if m_inc:
                    current_inc = int(m_inc.group(1))

            # Table for node set N_RP
            if "THE FOLLOWING TABLE IS PRINTED FOR NODES BELONGING TO NODE SET N_RP" in line:
                in_rp_table = True
            elif in_rp_table:
                if "MAXIMUM" in line or "MINIMUM" in line or "PAGE" in line or "Page" in line:
                    in_rp_table = False
                elif "999999" in line:
                    parts = line.split()
                    if len(parts) >= 3 and parts[0] == "999999":
                        try:
                            u2 = float(parts[1])
                            rf2_kN = float(parts[2])
                            rf2_N = rf2_kN * 1000.0
                            records.append({
                                "step": current_step,
                                "increment": current_inc,
                                "u2_mm": u2,
                                "rf2_kN": rf2_kN,
                                "rf2_N": rf2_N
                            })
                        except ValueError:
                            pass
                        in_rp_table = False

    return records


def parse_dat_nodal_displacements(dat_path: str) -> Dict[Tuple[int, int], Dict[int, Tuple[float, float, float]]]:
    """
    Parse all nodal tables (U1, U2, U3) from Abaqus .dat file for each (step, inc).
    In the Kinematic-Offset formulation:
    - U1 = delta u_x
    - U2 = delta u_y
    - U3 = delta d (pointwise damage correction)
    """
    tables = {}
    current_step = None
    current_inc = None
    in_table = False
    key = None

    if not os.path.exists(dat_path):
        return tables

    with open(dat_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            m_step_inc = re.search(r"STEP\s+(\d+)\s+INCREMENT\s+(\d+)", line)
            if m_step_inc:
                current_step = int(m_step_inc.group(1))
                current_inc = int(m_step_inc.group(2))
            else:
                m_inc = re.search(r"INCREMENT\s+(\d+)\s+SUMMARY", line)
                if m_inc:
                    current_inc = int(m_inc.group(1))

            if "THE FOLLOWING TABLE IS PRINTED FOR ALL NODES" in line:
                in_table = True
                key = (current_step, current_inc)
                if key not in tables:
                    tables[key] = {}
            elif in_table:
                if "MAXIMUM" in line or "MINIMUM" in line:
                    in_table = False
                elif line.strip() and not any(k in line for k in ["NODE", "NOTE", "PAGE", "Page", "Abaqus"]):
                    parts = line.split()
                    if len(parts) >= 4:
                        try:
                            nid = int(parts[0])
                            u1 = float(parts[1])
                            u2 = float(parts[2])
                            u3 = float(parts[3])
                            tables[key][nid] = (u1, u2, u3)
                        except ValueError:
                            pass

    return tables


def parse_energy_balance_csv(csv_path: str) -> List[Dict[str, Any]]:
    """
    Parse uel_energy_balance.csv generated by the Kinematic-Offset UEL.
    Returns list of records with elastic, fracture, and total energy in kN*mm (J) and mJ.
    """
    records = []
    if not os.path.exists(csv_path):
        return records

    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                step = int(row["Step"].strip())
                inc = int(row["Increment"].strip())
                e_elas_knmm = float(row["E_elastic_kNmm"].strip())
                e_frac_knmm = float(row["E_fracture_kNmm"].strip())
                e_tot_knmm = float(row["E_total_kNmm"].strip())
                records.append({
                    "step": step,
                    "increment": inc,
                    "e_elastic_knmm": e_elas_knmm,
                    "e_fracture_knmm": e_frac_knmm,
                    "e_total_knmm": e_tot_knmm,
                    "e_elastic_mJ": e_elas_knmm * 1000.0,
                    "e_fracture_mJ": e_frac_knmm * 1000.0,
                    "e_total_mJ": e_tot_knmm * 1000.0
                })
            except (KeyError, ValueError):
                pass
    return records


def evaluate_offset_simulation(evidence_dir: str, inp_prefix: str) -> Dict[str, Any]:
    """
    Comprehensive evaluation of an experimental offset simulation.
    Extracts reaction forces, damage changes, and energy metrics.
    """
    ev_path = Path(evidence_dir)
    dat_path = ev_path / f"{inp_prefix}.dat"
    csv_path = ev_path / "uel_energy_balance.csv"
    sta_path = ev_path / f"{inp_prefix}.sta"

    rp_records = parse_dat_rp_reactions(str(dat_path))
    nodal_tables = parse_dat_nodal_displacements(str(dat_path))
    energy_records = parse_energy_balance_csv(str(csv_path))

    # Identify Step 1 (reconstruction) and Step 2 (continuation)
    step1_rf = None
    step2_rf_list = []
    for r in rp_records:
        if r["step"] == 1 and r["increment"] == 1:
            step1_rf = r
        elif r["step"] == 2:
            step2_rf_list.append(r)

    # Damage metrics for Step 1 Inc 1
    damage_metrics_step1 = {}
    if (1, 1) in nodal_tables:
        t1 = nodal_tables[(1, 1)]
        u3_vals = [v[2] for v in t1.values()]
        if u3_vals:
            min_delta_d = min(u3_vals)
            max_delta_d = max(u3_vals)
            healing_count = sum(1 for v in u3_vals if v < -1e-6)
            growing_count = sum(1 for v in u3_vals if v > 1e-6)
            damage_metrics_step1 = {
                "min_delta_d": min_delta_d,
                "max_delta_d": max_delta_d,
                "healing_nodes_count": healing_count,
                "growing_nodes_count": growing_count,
                "total_nodes": len(u3_vals),
                "healing_detected": (min_delta_d < -1e-6)
            }

    # Energy metrics
    step1_energy = None
    step2_energy_list = []
    dissipation_monotonic = True
    prev_e_frac = 0.0

    for idx, e in enumerate(energy_records):
        if e["step"] == 1 and e["increment"] == 1:
            step1_energy = e
            prev_e_frac = e["e_fracture_knmm"]
        elif e["step"] == 2:
            step2_energy_list.append(e)
            if e["e_fracture_knmm"] < prev_e_frac - 1e-12:
                dissipation_monotonic = False
            prev_e_frac = e["e_fracture_knmm"]

    # Solver completion status
    analysis_completed = False
    if sta_path.exists():
        with open(sta_path, "r", encoding="utf-8", errors="replace") as f:
            sta_text = f.read()
        if "THE ANALYSIS HAS COMPLETED SUCCESSFULLY" in sta_text:
            analysis_completed = True

    return {
        "inp_prefix": inp_prefix,
        "evidence_dir": str(ev_path),
        "analysis_completed": analysis_completed,
        "step1_rf": step1_rf,
        "step2_rf_list": step2_rf_list,
        "step2_endpoint_rf": step2_rf_list[-1] if step2_rf_list else None,
        "damage_step1": damage_metrics_step1,
        "step1_energy": step1_energy,
        "step2_energy_list": step2_energy_list,
        "dissipation_monotonic": dissipation_monotonic
    }
