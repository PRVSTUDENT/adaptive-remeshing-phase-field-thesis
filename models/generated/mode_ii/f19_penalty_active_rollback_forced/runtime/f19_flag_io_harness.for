      PROGRAM F19_FLAG_IO_HARNESS
      CHARACTER*512 MODEPATH,STATEPATH
      INTEGER MODE,STATE,IOS
      MODEPATH='f19_harness_force_mode.flag'
      STATEPATH='f19_harness_cutback_state.flag'
      CALL F19_READ_FLAG(MODEPATH,MODE,IOS)
      IF (IOS.NE.0) THEN
       WRITE(*,*) 'F19_HARNESS_MODE_FAIL',IOS
       STOP 11
      ENDIF
      CALL F19_READ_FLAG(STATEPATH,STATE,IOS)
      IF (IOS.NE.0) THEN
       WRITE(*,*) 'F19_HARNESS_STATE_FAIL',IOS
       STOP 12
      ENDIF
      IF (MODE.EQ.1.AND.STATE.EQ.0) THEN
       CALL F19_WRITE_STATE(STATEPATH,1,IOS)
       IF (IOS.NE.0) THEN
        WRITE(*,*) 'F19_HARNESS_TRANSITION_FAIL',IOS
        STOP 13
       ENDIF
      ENDIF
      CALL F19_READ_FLAG(STATEPATH,STATE,IOS)
      IF (IOS.NE.0) STOP 14
      WRITE(*,*) 'F19_HARNESS_PASS',MODE,STATE
      END

      SUBROUTINE F19_READ_FLAG(PATH,VALUE,IOS)
      CHARACTER*(*) PATH
      INTEGER VALUE,IOS,CIOS
      LOGICAL EXISTS
      VALUE=-1
      IOS=0
      INQUIRE(FILE=TRIM(PATH),EXIST=EXISTS,IOSTAT=IOS)
      IF (IOS.NE.0) RETURN
      IF (.NOT.EXISTS) THEN
       IOS=1001
       RETURN
      ENDIF
      OPEN(UNIT=97,FILE=TRIM(PATH),STATUS='OLD',ACTION='READ',IOSTAT=IOS)
      IF (IOS.NE.0) RETURN
      READ(97,*,IOSTAT=IOS) VALUE
      CLOSE(97,IOSTAT=CIOS)
      IF (IOS.EQ.0.AND.CIOS.NE.0) IOS=CIOS
      IF (IOS.NE.0) RETURN
      IF (VALUE.NE.0.AND.VALUE.NE.1) IOS=1002
      RETURN
      END

      SUBROUTINE F19_WRITE_STATE(PATH,VALUE,IOS)
      CHARACTER*(*) PATH
      INTEGER VALUE,IOS,CIOS
      LOGICAL EXISTS
      IOS=0
      INQUIRE(FILE=TRIM(PATH),EXIST=EXISTS,IOSTAT=IOS)
      IF (IOS.NE.0) RETURN
      IF (.NOT.EXISTS) THEN
       IOS=1003
       RETURN
      ENDIF
      IF (VALUE.NE.0.AND.VALUE.NE.1) THEN
       IOS=1004
       RETURN
      ENDIF
      OPEN(UNIT=97,FILE=TRIM(PATH),STATUS='OLD',ACTION='WRITE',IOSTAT=IOS)
      IF (IOS.NE.0) RETURN
      WRITE(97,'(I1)',IOSTAT=IOS) VALUE
      CLOSE(97,IOSTAT=CIOS)
      IF (IOS.EQ.0.AND.CIOS.NE.0) IOS=CIOS
      RETURN
      END
